"""
Pydantic data models for Phase 4: Groq AI Recommendation.
Defines structured schema for recommendations, justifications, and responses.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class RecommendedRestaurant(BaseModel):
    """An individual restaurant recommended by the Groq AI model with reasoning."""

    restaurant_name: str = Field(..., description="Name of the restaurant")
    location: str = Field(..., description="Locality or neighborhood")
    cost_for_two: int = Field(..., gt=0, description="Approximate cost for two people in INR")
    rating: float = Field(..., ge=0.0, le=5.0, description="Zomato aggregate rating out of 5.0")
    cuisines: str = Field(default="", description="Cuisines served")
    ai_rationale: str = Field(
        ...,
        description="2-sentence AI justification explaining why this spot fits user budget and location",
    )
    must_try_dishes: List[str] = Field(
        default_factory=list,
        description="Curated must-try dishes based on customer review highlights",
    )
    budget_verdict: str = Field(
        default="",
        description="Concise budget evaluation, e.g., 'Rs. 200 under your budget'",
    )
    online_order: str = Field(default="No", description="Whether online delivery is supported")
    book_table: str = Field(default="No", description="Whether table reservations are supported")


class RecommendationResponse(BaseModel):
    """Complete recommendation response package generated by Step 4."""

    query_summary: Dict[str, Any] = Field(
        ...,
        description="Summary of the applied user constraints (city, budget, preferences)",
    )
    recommendations: List[RecommendedRestaurant] = Field(
        default_factory=list,
        description="Top 3 to 5 ranked restaurant recommendations",
    )
    overall_ai_summary: str = Field(
        ...,
        description="Concise concierge overview of the dining options found",
    )
    model_name: str = Field(default="groq", description="Name of the model used")
    latency_seconds: float = Field(default=0.0, description="Inference latency in seconds")
    is_mock: bool = Field(default=False, description="Whether generated via mock fallback")

